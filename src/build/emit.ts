/**
 * Element traversal: dispatches IR elements to the text / shape / image emitters and records groups.
 *
 * Every emitter returns the names (`fd:<n>`) of the top-level objects it wrote, in z-order. A group with
 * at least two emitted members becomes a `ManifestGroup` (wrapped into `<p:grpSp>` by post/) when
 * `preserveGroups` is on; otherwise its members stay flat.
 */
import type PptxGenJS from 'pptxgenjs';
import type { Element, GroupElement, TextElement } from '../ir/types';
import { rotatedBounds, unionRects, type SlideContext } from './context';
import { shadowEffectXml } from './effects';
import { emitImage } from './images';
import type { EmuRect } from './manifest';
import { emitShape } from './shapes';
import { textBodySpec, textBoxTransform } from './text';
import { emuArg } from './units';

const VALIGN: Record<TextElement['verticalAlign'], PptxGenJS.VAlign> = { top: 'top', middle: 'middle', bottom: 'bottom' };

/** Emit a text element as a text box; the body is generated by textBody.ts and swapped in by post/. */
export function emitText(ctx: SlideContext, el: TextElement): string[] {
  const link = ctx.linkIndex(el.hyperlink, el.id, el.name);
  const t = textBoxTransform(el, ctx.options.widthSlackPercent);
  const box = ctx.transformEmu(t);
  const name = ctx.nextName();
  const opts: PptxGenJS.TextPropsOptions = {
    x: emuArg(box.x),
    y: emuArg(box.y),
    w: emuArg(Math.max(1, box.w)),
    // pptxgenjs replaces a 0 height with 0.3″.
    h: emuArg(Math.max(1, box.h)),
    objectName: name,
    isTextBox: true,
    margin: 0,
    valign: VALIGN[el.verticalAlign] ?? 'top',
  };
  if (box.rotation) opts.rotate = box.rotation;
  if (box.flipH) opts.flipH = true;
  if (box.flipV) opts.flipV = true;
  // Placeholder run: the whole <p:txBody> is replaced in post/.
  ctx.pptSlide.addText([{ text: ' ' }], opts);

  const fonts = ctx.state.fonts;
  const body = textBodySpec(el, {
    scale: ctx.scale,
    opacity: el.opacity,
    textCase: ctx.options.textCase,
    font: (family, style) => fonts.use(family, style),
    endFont: (family, style) => fonts.resolve(family, style),
    linkIndex: (h) => ctx.linkIndex(h, el.id, el.name),
  });
  ctx.addObject({
    kind: 'text',
    name,
    layerName: el.name,
    bounds: rotatedBounds(box, box.rotation),
    link,
    effectLst: el.shadow ? shadowEffectXml(el.shadow, ctx.scale, el.opacity) : null,
    body,
  });
  ctx.state.stats.texts++;
  return [name];
}

/** Give members without their own click action the group's hyperlink (flattened groups). */
function inheritLink(ctx: SlideContext, names: ReadonlyArray<string>, link: number): void {
  for (const name of names) {
    const target = ctx.lookup(name);
    if (target && target.link === null) target.link = link;
  }
}

export function emitGroup(ctx: SlideContext, g: GroupElement): string[] {
  if (g.shadow) {
    ctx.addReport('warning', 'effect-dropped', 'Shadows on groups are not supported natively and were dropped.', g.id, g.name, 'GROUP');
  }
  const members = emitElements(ctx, g.children ?? []);
  const link = ctx.linkIndex(g.hyperlink, g.id, g.name);
  if (!ctx.options.preserveGroups || members.length < 2) {
    if (link !== null) inheritLink(ctx, members, link);
    return members;
  }
  const rects = members.map((m) => ctx.lookup(m)?.bounds).filter((r): r is EmuRect => r !== undefined);
  const u = unionRects(rects) ?? ctx.rectEmu(g.transform);
  const name = ctx.nextName();
  ctx.addGroup({
    name,
    layerName: g.name,
    members,
    bounds: { x: u.x, y: u.y, w: Math.max(1, u.w), h: Math.max(1, u.h) },
    link,
  });
  ctx.state.stats.groups++;
  return [name];
}

export function emitElement(ctx: SlideContext, el: Element): string[] {
  if (el.type !== 'group' && el.shadow && el.shadow.spread) {
    ctx.addReport('warning', 'effect-approximated', `Shadow spread ${el.shadow.spread}px is not supported natively and was ignored.`, el.id, el.name);
  }
  switch (el.type) {
    case 'text':
      return emitText(ctx, el);
    case 'shape':
      return emitShape(ctx, el);
    case 'image':
      return emitImage(ctx, el);
    case 'group':
      return emitGroup(ctx, el);
    default: {
      const unknown = el as { id?: string; name?: string; type?: string };
      ctx.addReport('warning', 'unsupported-element', `Unknown element type "${String(unknown.type)}" skipped.`, unknown.id, unknown.name);
      return [];
    }
  }
}

/** Emit elements back to front; returns the top-level names written. */
export function emitElements(ctx: SlideContext, elements: ReadonlyArray<Element>): string[] {
  const names: string[] = [];
  for (const el of elements) names.push(...emitElement(ctx, el));
  return names;
}
